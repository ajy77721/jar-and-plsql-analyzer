-- ============================================================================
-- Oracle cross-schema REFERENCE seed  (run as SYSDBA)
--   creates a SECOND user/schema : ANALYZER_REF   password : Password123!
--   objects owned by ANALYZER_REF are referenced cross-schema by ANALYZER.
--
-- Run as SYSDBA, e.g. inside the container:
--   sqlplus / as sysdba @/tmp/oracle_ref.sql
--
-- Idempotent: DROP USER ANALYZER_REF CASCADE (if exists) then recreate.
-- ============================================================================

SET DEFINE OFF
WHENEVER SQLERROR CONTINUE

ALTER SESSION SET CONTAINER = FREEPDB1;

-- ---------------------------------------------------------------- clean slate
BEGIN
  EXECUTE IMMEDIATE 'DROP USER ANALYZER_REF CASCADE';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -1918 THEN  -- ORA-01918: user does not exist
      RAISE;
    END IF;
END;
/

-- ---------------------------------------------------------------- create user
CREATE USER ANALYZER_REF IDENTIFIED BY "Password123!"
  DEFAULT TABLESPACE USERS
  QUOTA UNLIMITED ON USERS;

GRANT CREATE SESSION, CREATE TABLE, CREATE VIEW, CREATE PROCEDURE,
      CREATE TRIGGER, CREATE SEQUENCE TO ANALYZER_REF;

-- ---------------------------------------------------------------- table + data
CREATE TABLE ANALYZER_REF.REF_REGION (
  region_id   NUMBER        NOT NULL,
  region_name VARCHAR2(60),
  active      NUMBER        DEFAULT 1,
  CONSTRAINT pk_ref_region PRIMARY KEY (region_id)
);

INSERT INTO ANALYZER_REF.REF_REGION (region_id, region_name, active) VALUES (1, 'NORTH AMERICA', 1);
INSERT INTO ANALYZER_REF.REF_REGION (region_id, region_name, active) VALUES (2, 'EUROPE',        1);
INSERT INTO ANALYZER_REF.REF_REGION (region_id, region_name, active) VALUES (3, 'ASIA PACIFIC',  1);
INSERT INTO ANALYZER_REF.REF_REGION (region_id, region_name, active) VALUES (4, 'LATIN AMERICA', 0);
COMMIT;

-- ---------------------------------------------------------------- view
CREATE OR REPLACE VIEW ANALYZER_REF.VW_REGION AS
  SELECT region_id, region_name, active
  FROM ANALYZER_REF.REF_REGION
  WHERE active = 1;

-- ---------------------------------------------------------------- audit table
CREATE TABLE ANALYZER_REF.REF_AUDIT (
  audit_id  NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  event     VARCHAR2(60),
  message   VARCHAR2(400),
  logged_at TIMESTAMP DEFAULT SYSTIMESTAMP,
  CONSTRAINT pk_ref_audit PRIMARY KEY (audit_id)
);

-- ---------------------------------------------------------------- function
CREATE OR REPLACE FUNCTION ANALYZER_REF.FN_REGION_NAME(p_id NUMBER)
  RETURN VARCHAR2
IS
  v_name ANALYZER_REF.REF_REGION.region_name%TYPE;
BEGIN
  SELECT region_name INTO v_name
  FROM ANALYZER_REF.REF_REGION
  WHERE region_id = p_id;
  RETURN v_name;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RETURN NULL;
END FN_REGION_NAME;
/

-- ---------------------------------------------------------------- procedure
CREATE OR REPLACE PROCEDURE ANALYZER_REF.USP_REF_LOG(
  p_event   IN VARCHAR2,
  p_message IN VARCHAR2
)
IS
BEGIN
  INSERT INTO ANALYZER_REF.REF_AUDIT(event, message)
  VALUES (p_event, SUBSTR(p_message, 1, 400));
  COMMIT;
END USP_REF_LOG;
/

-- ---------------------------------------------------------------- trigger
CREATE OR REPLACE TRIGGER ANALYZER_REF.TRG_REF_REGION
AFTER INSERT ON ANALYZER_REF.REF_REGION
FOR EACH ROW
BEGIN
  INSERT INTO ANALYZER_REF.REF_AUDIT(event, message)
  VALUES ('REGION_INSERT', 'region_id=' || :NEW.region_id);
END TRG_REF_REGION;
/

-- ---------------------------------------------------------------- grants to ANALYZER
GRANT SELECT  ON ANALYZER_REF.REF_REGION     TO ANALYZER;
GRANT SELECT  ON ANALYZER_REF.VW_REGION      TO ANALYZER;
GRANT INSERT  ON ANALYZER_REF.REF_REGION     TO ANALYZER;
GRANT EXECUTE ON ANALYZER_REF.FN_REGION_NAME TO ANALYZER;
GRANT EXECUTE ON ANALYZER_REF.USP_REF_LOG    TO ANALYZER;

-- ---------------------------------------------------------------- confirm
SELECT object_type, COUNT(*) AS n
FROM dba_objects
WHERE owner = 'ANALYZER_REF'
GROUP BY object_type
ORDER BY object_type;

EXIT
</content>
</invoke>
