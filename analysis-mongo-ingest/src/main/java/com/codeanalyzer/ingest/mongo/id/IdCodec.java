package com.codeanalyzer.ingest.mongo.id;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;

/**
 * The only place an {@code _id} is constructed.
 *
 * <h2>Why one class</h2>
 *
 * <p>An id scheme spread across thirty mappers is an id scheme with thirty subtly different
 * escaping bugs, and the failure mode is silent: two keys that should differ collide, one upsert
 * overwrites the other, and the row is simply gone. Everything that needs an id asks here.
 *
 * <h2>Deterministic, and computed before the write</h2>
 *
 * <p>Every id is a pure function of natural keys already present in the source JSON. Nothing is
 * generated by the database and nothing is read back, so a parent and all of its children can be
 * written in any order, by any number of workers, and the references between them are already
 * correct. That is the whole reason the scheme is not a surrogate {@code ObjectId} or a UUID:
 * a random id must be read back before a child can point at it.
 *
 * <h2>The length rule</h2>
 *
 * <p>Ids up to {@link #MAX_PLAIN_ID_BYTES} are stored as readable text. Longer ones are stored as
 * {@code <collection>~sha256:<hex>} and the readable form is kept in the document's {@code _key}
 * field, which is indexed. Measured: only a handful of collections ever exceed the threshold —
 * {@code java_method} peaks at 1,025 bytes because a Spring constructor descriptor spells out
 * every injected parameter type.
 *
 * <p>MongoDB 4.2 removed the hard 1,024-byte index-key limit, and this server (6.0.26, FCV 6.0)
 * would accept the long ids. Hashing is not about legality: a 1 KB id repeated across an index is
 * roughly 110 MB of index for a 12 MB collection, and relying on a limit that was only recently
 * removed makes the schema depend on the server version it happens to meet.
 */
public final class IdCodec {

    /** Above this many UTF-8 bytes the plaintext id is replaced by a hash. */
    public static final int MAX_PLAIN_ID_BYTES = 256;

    private IdCodec() {}

    /** Builds an identity for {@code collection} from natural-key {@code parts}. */
    public static Ids of(String collection, String... parts) {
        return fromKey(collection, Escaping.join(parts));
    }

    /**
     * Builds an identity that extends an existing id with further components.
     *
     * <p>The parent id is appended <b>as-is</b> rather than escaped as a single component. Escaping
     * it produced ids like {@code ORACLE\~ORACLEDEMO\~LOCAL\~ERP\~v1~ANALYZER~ERP_SALES_ORDER},
     * where the parent's own separators were escaped a second time — correct, but unreadable, and
     * the noise compounds with every level of nesting.
     *
     * <p>Appending unescaped is unambiguous because <b>arity is fixed per collection</b>: an
     * {@code am_db_object} id is always exactly the run's four components plus two. Nothing can
     * therefore mistake a five-and-one split for a four-and-two one, because only one of those is
     * a legal shape for this collection. That is the property that makes this safe, and it stops
     * being true the moment a recipe takes a variable number of components — so none does.
     */
    public static Ids nested(String collection, String parentId, String... parts) {
        StringBuilder sb = new StringBuilder(parentId);
        for (String part : parts) sb.append(Escaping.SEP).append(Escaping.escape(part));
        return fromKey(collection, sb.toString());
    }

    private static Ids fromKey(String collection, String key) {
        byte[] raw = key.getBytes(StandardCharsets.UTF_8);
        if (raw.length <= MAX_PLAIN_ID_BYTES) return new Ids(key, key);
        return new Ids(collection + "~sha256:" + sha256Hex(raw), key);
    }

    // ── Per-collection recipes. Named methods, not free-form strings, so a caller cannot
    //    accidentally build a key with the components in a different order. ──────────────

    /** {@code am_run}: DIALECT~PROJECT~ENV~ENTRY~vN. The prefix of every other id. */
    public static Ids run(String dialect, String project, String env, String entryPoint, int version) {
        return of("am_run", dialect, project, env, entryPoint, "v" + version);
    }

    /** {@code am_db_object}: run ~ schema ~ objectName. */
    public static Ids dbObject(String runId, String schema, String name) {
        return nested("am_db_object", runId, schema, name);
    }

    // dbColumn(objectId, columnName) was here, keying a collection called am_db_column. Deleted
    // 2026-09-07 with the naming decision in registry §17: db columns are an array, the no-arrays
    // invariant splits them into am_db_object__db_columns, and split children are keyed by
    // Splitter rather than from here. It never had a caller.

    /**
     * {@code am_sequence_obj}: run ~ schema ~ sequenceName.
     *
     * <p>Run-scoped like {@link #dbObject}, and for the same reason: a sequence belongs to a schema
     * as analysed, and two runs of different databases can hold the same name.
     */
    public static Ids sequenceObj(String runId, String schema, String name) {
        return nested("am_sequence_obj", runId, schema, name);
    }

    /** {@code am_analysis_advice}: jar ~ ordinal within the advice array. */
    public static Ids analysisAdvice(String jarKey, int ordinal) {
        return nested("am_analysis_advice", jarKey, String.valueOf(ordinal));
    }

    /**
     * {@code am_table_column_usage}: object ~ columnName.
     *
     * <p>One aggregate row per (table, column) — the entity the data-model audit nearly lost,
     * carrying the per-column rollup no other document holds.
     */
    public static Ids tableColumnUsage(String objectId, String columnName) {
        return nested("am_table_column_usage", objectId, columnName);
    }

    /** {@code am_proc_node}: run ~ nodeId. */
    public static Ids procNode(String runId, String nodeId) {
        return nested("am_proc_node", runId, nodeId);
    }

    /**
     * A child of a node, keyed by its position in the source.
     *
     * <p>{@code kind} distinguishes the collections so a cursor and an exception handler declared
     * on the same line cannot share an id. {@code ordinal} disambiguates two of the same kind on
     * one line — which does occur, and without it the second would silently overwrite the first.
     */
    public static Ids nodeChild(String collection, String nodeId, String kind, int line, int ordinal) {
        return nested(collection, nodeId, kind, String.valueOf(line), String.valueOf(ordinal));
    }

    /** {@code am_subtree_table} / {@code am_node_table_access}: node ~ schema ~ table. */
    public static Ids nodeObjectRow(String collection, String nodeId, String schema, String table) {
        return nested(collection, nodeId, schema, table);
    }

    /**
     * {@code am_statement}: node ~ operation ~ line ~ schema ~ table.
     *
     * <p><b>Five parts, not three.</b> {@code (nodeId, operation, line)} is NOT unique: measured
     * across the corpus it collides on 63 ORACLE rows, 81 POSTGRES and 64 DB2, because one
     * statement can touch several tables at the same line. Keyed on three parts, ingest would
     * upsert those rows on top of each other and 208 statements would silently vanish — a loss
     * that no error reports and no count reveals unless you already know to look.
     *
     * <p>Adding schema and table makes it unique in all five dialects, verified on real data.
     */
    public static Ids statement(String nodeEntityKey, String operation, int line,
                                String schema, String table) {
        return nested("am_statement", nodeEntityKey, operation, String.valueOf(line), schema, table);
    }

    /** {@code am_sql_text}: content-addressed, because 73% of captured SQL is duplicated. */
    public static Ids sqlText(String hashHex) {
        return of("am_sql_text", hashHex);
    }

    /**
     * {@code am_call_edge}: one call occurrence — from ~ to ~ line.
     *
     * <p>Depth is deliberately not in the key. It was the obvious fourth component, and measuring
     * showed it adds nothing: {@code (from, to, line)} is already unique in all five dialects
     * (2,258 / 3,295 / 428 / 652 / 337 rows, no collisions). A key component that never
     * discriminates is pure cost — it lengthens every id and every index entry.
     */
    /**
     * {@code am_call_edge}: one call occurrence.
     *
     * <p>Deliberately <b>not</b> scoped by run. A call from one procedure to another at a given
     * line is the same fact in every run of the same source, and putting the run id in the key made
     * every run produce fresh entities: measured across four archived POSTGRES runs, this one
     * collection deduplicated at 0% while every other sat at exactly 75%, dragging the whole
     * analysis down to 40.9%. It is also the largest PL/SQL collection, so it dominated the total.
     *
     * <p>Safe because the triple is already unique within a run — measured 3,295 edges and 3,295
     * distinct {@code (from, to, line)} triples in one POSTGRES run. The run a given edge belongs
     * to is recorded by its {@code am_run_member} row, which is what membership is for.
     */
    public static Ids callEdge(String from, String to, int line) {
        return nested("am_call_edge", from, to, String.valueOf(line));
    }

    /**
     * {@code am_call_edge_unique}: the aggregated edge — from ~ to, one per pair.
     *
     * <p>Run-independent for the same reason as {@link #callEdge}. The aggregate fields it carries
     * ({@code count}, {@code lines}, {@code minDepth}) are properties of the analysed source, so two
     * runs of identical source produce an identical document and collapse to one.
     */
    public static Ids callEdgeUnique(String from, String to) {
        return nested("am_call_edge_unique", from, to);
    }

    /** {@code am_java_class}: the fully-qualified name is already globally unique. */
    public static Ids javaClass(String jarKey, String fqn) {
        return nested("am_java_class", jarKey, fqn);
    }

    /**
     * {@code am_java_method}: class ~ name ~ descriptor.
     *
     * <p>The JVM itself guarantees this triple is unique — two methods of one class cannot share a
     * name and descriptor — so this is a genuine natural key rather than one we hope holds. Name
     * alone would not do: 33,409 methods reduce to 11,976 distinct name/descriptor pairs, because
     * {@code toString()} recurs in hundreds of classes. Those are different methods with different
     * code, and merging them would be data loss disguised as deduplication.
     *
     * <p>This is also the id most likely to be hashed: a Spring constructor descriptor listing
     * every injected type reached 1,025 bytes when measured.
     */
    public static Ids javaMethod(String classKey, String name, String descriptor) {
        return nested("am_java_method", classKey, name, descriptor);
    }

    /** {@code am_java_field}: class ~ field name. */
    public static Ids javaField(String classKey, String name) {
        return nested("am_java_field", classKey, name);
    }

    /** {@code am_invocation}: pooled call target, keyed by its index in the pool. */
    public static Ids invocation(String jarKey, int poolIndex) {
        return nested("am_invocation", jarKey, String.valueOf(poolIndex));
    }

    /** {@code am_method_invocation}: the junction — method ~ pooled target ~ ordinal. */
    public static Ids methodInvocation(String methodKey, int poolIndex, int ordinal) {
        return nested("am_method_invocation", methodKey,
                String.valueOf(poolIndex), String.valueOf(ordinal));
    }

    /**
     * {@code am_dag_node}: the producer's own 20-hex content hash.
     *
     * <p>Nothing is invented here. The call-tree is already content-addressed upstream — identical
     * subtrees share a key — which is why 3,784 physical nodes stand in for 20.3 billion logical
     * ones. Re-deriving an id would throw that away; the design's only job is not to destroy it.
     */
    public static Ids dagNode(String jarKey, String hash) {
        return nested("am_dag_node", jarKey, hash);
    }

    /** {@code am_dag_edge}: parent ~ ordinal ~ child. Ordinal because call order is meaningful. */
    public static Ids dagEdge(String parentKey, int ordinal, String childHash) {
        return nested("am_dag_edge", parentKey, String.valueOf(ordinal), childHash);
    }

    /**
     * {@code am_endpoint}: jar ~ controller ~ method ~ httpMethod ~ path.
     *
     * <p>Measured on the real data: {@code controllerClass + methodName} is already unique across
     * all 321 endpoints, and {@code controllerClass} alone is emphatically not — a first attempt
     * fell back to it and collapsed every endpoint of a controller into one row, which the unique
     * index caught. The HTTP method and path are included anyway, because two overloads of one
     * handler would defeat the shorter key and the failure would be silent under an upsert.
     */
    public static Ids endpoint(String jarKey, String controller, String method,
                               String httpMethod, String path) {
        return nested("am_endpoint", jarKey, controller, method, httpMethod, path);
    }

    /** {@code am_endpoint_pool}: jar ~ pool name ~ index. */
    public static Ids endpointPool(String jarKey, String pool, int index) {
        return nested("am_endpoint_pool", jarKey, pool, String.valueOf(index));
    }

    private static String sha256Hex(byte[] raw) {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(raw));
        } catch (NoSuchAlgorithmException e) {
            // SHA-256 is mandated by the JLS for every conforming JVM; if it is missing the
            // environment is broken in a way this module cannot sensibly work around.
            throw new IllegalStateException("SHA-256 unavailable", e);
        }
    }
}
